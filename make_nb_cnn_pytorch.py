    "# Split Train & Validation\n",
    "X_tr, X_val, y_tr, y_val = train_test_split(X_train, y_train, test_size=0.2, random_state=42, stratify=y_train)\n",
    "\n",
    "# Menangani Ketidakseimbangan Data (Class Weights)\n",
    "class_sample_count = np.array([len(np.where(y_tr == t)[0]) for t in np.unique(y_tr)])\n",
    "weight = 1. / class_sample_count\n",
    "samples_weight = np.array([weight[t] for t in y_tr])\n",
    "samples_weight = torch.from_numpy(samples_weight).double()\n",
    "sampler = WeightedRandomSampler(samples_weight, len(samples_weight))\n",
    "\n",
    "# Buat DataLoader\n",
    "train_dataset = TensorDataset(torch.tensor(X_tr), torch.tensor(y_tr))\n",
    "train_loader = DataLoader(train_dataset, batch_size=32, sampler=sampler)\n",
    "\n",
    "val_dataset = TensorDataset(torch.tensor(X_val), torch.tensor(y_val))\n",
    "val_loader = DataLoader(val_dataset, batch_size=32, shuffle=False)"
