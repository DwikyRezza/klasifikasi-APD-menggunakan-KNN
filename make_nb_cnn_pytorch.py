    "def classify_demo_pytorch(image_path, cnn_model):\n",
    "    img = cv2.imread(image_path)\n",
    "    if img is None:\n",
    "        return \"Error\"\n",
    "    \n",
    "    img_resized = cv2.resize(img, IMG_SIZE)\n",
    "    img_rgb = cv2.cvtColor(img_resized, cv2.COLOR_BGR2RGB)\n",
    "    \n",
    "    img_tensor = np.transpose(img_rgb, (2, 0, 1)).astype(np.float32) / 255.0\n",
    "    input_tensor = torch.tensor(img_tensor).unsqueeze(0).to(device)\n",
    "    \n",
    "    cnn_model.eval()\n",
    "    with torch.no_grad():\n",
    "        output = cnn_model(input_tensor).squeeze()\n",
    "        prob = torch.sigmoid(output).item()\n",
    "        \n",
    "    pred_id = 1 if prob > 0.5 else 0\n",
    "    predicted_label = \"Kacamata\" if pred_id == 1 else \"Helm\"\n",
    "    \n",
    "    plt.figure(figsize=(4, 4))\n",
    "    plt.imshow(img_rgb)\n",
    "    plt.title(f\"CNN: {predicted_label} (Prob Kacamata: {prob:.2f})\")\n",
    "    plt.axis(\"off\")\n",
    "    plt.show()\n",
    "    \n",
    "    return predicted_label\n",
