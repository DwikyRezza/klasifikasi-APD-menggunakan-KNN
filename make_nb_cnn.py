    "import cv2\n",
    "import numpy as np\n",
    "import os\n",
    "import glob\n",
    "from tqdm.notebook import tqdm\n",
    "import matplotlib.pyplot as plt\n",
    "\n",
    "IMG_SIZE = (64, 64)\n",
    "\n",
    "def load_data(data_dir):\n",
    "    categories = {\"helm\": 0, \"kacamata\": 1}\n",
    "    X, y = [], []\n",
    "    for label_name, label_id in categories.items():\n",
    "        folder = os.path.join(data_dir, label_name)\n",
    "        files = glob.glob(os.path.join(folder, \"*.*\"))\n",
    "        print(f\"Memproses '{label_name}': {len(files)} gambar ditemukan...\")\n",
    "        \n",
    "        for img_path in tqdm(files, desc=f\"Loading {label_name}\"):\n",
    "            img = cv2.imread(img_path)\n",
    "            if img is not None:\n",
    "                img_resized = cv2.resize(img, IMG_SIZE)\n",
    "                # Convert BGR ke RGB agar warna sesuai saat divisualisasi\n",
    "                img_rgb = cv2.cvtColor(img_resized, cv2.COLOR_BGR2RGB)\n",
    "                X.append(img_rgb)\n",
    "                y.append(label_id)\n",
    "    return np.array(X), np.array(y)\n",
    "\n",
    "print(\"Memuat Data Train...\")\n",
    "X_train, y_train = load_data(\"dataset/train\")\n",
    "\n",
    "# Normalisasi pixel menjadi rentang 0 sampai 1 untuk membantu Neural Network belajar\n",
    "X_train = X_train.astype('float32') / 255.0\n",
    "\n",
    "print(f\"\\nDimensi X_train: {X_train.shape} (Jumlah Data, Height, Width, Channels)\")\n",
    "print(f\"Dimensi y_train: {y_train.shape}\")"
