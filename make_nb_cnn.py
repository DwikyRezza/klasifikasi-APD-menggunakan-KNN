    "import tensorflow as tf\n",
    "from tensorflow.keras import layers, models\n",
    "\n",
    "# Membangun Arsitektur CNN\n",
    "model = models.Sequential([\n",
    "    # Layer Konvolusi Pertama\n",
    "    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(IMG_SIZE[0], IMG_SIZE[1], 3)),\n",
    "    layers.MaxPooling2D((2, 2)),\n",
    "    \n",
    "    # Layer Konvolusi Kedua\n",
    "    layers.Conv2D(64, (3, 3), activation='relu'),\n",
    "    layers.MaxPooling2D((2, 2)),\n",
    "    \n",
    "    # Layer Konvolusi Ketiga\n",
    "    layers.Conv2D(128, (3, 3), activation='relu'),\n",
    "    layers.MaxPooling2D((2, 2)),\n",
    "    \n",
    "    # Meratakan matriks untuk dimasukkan ke Dense Layer (Fully Connected)\n",
    "    layers.Flatten(),\n",
    "    layers.Dense(128, activation='relu'),\n",
    "    \n",
    "    # Dropout digunakan untuk mematikan neuron acak agar tidak overfitting\n",
    "    layers.Dropout(0.5),\n",
    "    \n",
    "    # Output layer menggunakan Sigmoid karena ini Binary Classification (0 atau 1)\n",
    "    layers.Dense(1, activation='sigmoid')\n",
    "])\n",
    "\n",
    "model.compile(optimizer='adam',\n",
    "              loss='binary_crossentropy',\n",
    "              metrics=['accuracy'])\n",
    "\n",
